function P = init_parameters()
%INIT_PARAMETERS Traceable parameters for the 5 MW averaged model.
P.base.S = 5e6;                 % VA
P.base.Vll = 690;               % V RMS line-line
P.base.f = 50;                  % Hz
P.base.w = 2*pi*P.base.f;
P.base.I = P.base.S/(sqrt(3)*P.base.Vll);
P.wind.rho = 1.225;             % kg/m^3
P.wind.R = 55;                  % m
P.wind.A = pi*P.wind.R^2;
P.wind.beta = 0;                % deg
P.wind.v_nom = 12;              % m/s
P.wind.lambda_opt = 6.3;
P.wind.omega_base = P.wind.lambda_opt*P.wind.v_nom/P.wind.R;
P.wind.v_step = P.wind.v_nom;
P.wind.t_step = 4;
P.pmsg.H = 4.0;                 % s
P.pmsg.D = 0.02;                % pu torque / pu speed
P.pmsg.Rs = 0.01;               % pu, documented machine loss proxy
P.pmsg.Ld = 0.25;               % pu
P.pmsg.Lq = 0.25;               % pu
P.pmsg.psi_pm = 1.0;            % pu
P.msc.Kp_speed = 2.0;
P.msc.Ki_speed = 1.0;
P.msc.tau_current = 0.02;       % s, averaged inner loop
P.dc.C_pu = 0.08;               % s, energy-normalized capacitance
P.dc.v_ref = 1.0;
P.gsc.Kp_current = 0.30;
P.gsc.Ki_current = 20.0;
P.gsc.Kp_dc = 0.80;
P.gsc.Ki_dc = 20.0;
P.filter.R = 0.01;              % pu
P.filter.X = 0.15;              % pu at 50 Hz
P.grid.E = 1.0;                 % pu infinite-bus voltage
P.grid.scr_initial = 10;
P.grid.scr_final = 10;
P.grid.xr = 10;
P.grid.t_disturbance = 2;
P.pll.Kp = 0.01;
P.pll.Ki_base = 2.80;
P.pll.Ki_mitigated = 0.50;
P.mitigation.enable = false;
P.sim.dt = 2e-4;               % s; converged per results/validation/numerical_sensitivity.csv
P.sim.t_end = 12;
P.sim.analysis_start = 3;
P.sim.case_name = 'baseline';
P.analysis.band = [1 45];
P.analysis.prony_order = 20;
P.meta.model_fidelity = 'nonlinear averaged dq full-converter model';
P.meta.parameter_version = '1.0.0';
end

function M = calculate_metrics(R)
%CALCULATE_METRICS Quantitative electrical and oscillation measures.
P=R.P; F=analyse_frequency(R.t,R.power_e,P.analysis.band,P.sim.analysis_start);
keep=R.t>=P.sim.analysis_start;
Pr=analyse_prony(R.t(keep),R.power_e(keep),P.analysis.prony_order,P.analysis.band,F.dominant_frequency);
E=analyse_eigenvalues(P,F.dominant_frequency);
late=R.t>=max(P.sim.analysis_start,R.t(end)-3);
M=struct('case_name',R.case_name,'sso_frequency_fft',F.dominant_frequency, ...
    'fft_amplitude',F.dominant_amplitude,'power_osc_rms',rms(detrend(R.power_e(late))), ...
    'peak_current_pu',max(R.current_pu),'vdc_max_deviation',max(abs(R.vdc-1)), ...
    'prony_frequency',Pr.frequency,'prony_sigma',Pr.sigma, ...
    'prony_damping_ratio',Pr.damping_ratio,'prony_fit_nrmse',Pr.fit_nrmse, ...
    'eigenvalue',E.critical_eigenvalue,'eigen_frequency',E.critical_frequency, ...
    'eigen_damping_ratio',E.critical_damping_ratio,'max_real_eigenvalue',E.max_real_part, ...
    'frequency_analysis',F,'prony',Pr,'eigenanalysis',E);
end

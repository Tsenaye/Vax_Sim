function export_model_snapshots()
root=init_project(); mdl='Vataleni_PMSG_SSO_Final'; load_system(fullfile(root,'model',[mdl '.slx']));
items={mdl,'top_level'; ...
    [mdl '/Wind Turbine + PMSG'],'turbine_pmsg'; ...
    [mdl '/MSC Control'],'msc_control'; ...
    [mdl '/DC Link'],'dc_link'; ...
    [mdl '/GSC Control'],'gsc_control'; ...
    [mdl '/PLL'],'pll'; ...
    [mdl '/Grid Current Dynamics'],'grid_current'; ...
    [mdl '/PCC Interface'],'pcc_interface'; ...
    [mdl '/Measurements and Analysis Interface'],'measurements'};
for k=1:size(items,1)
    open_system(items{k,1}); set_param(items{k,1},'ZoomFactor','FitSystem');
    print(['-s' items{k,1}],'-dpng','-r160',fullfile(root,'artifacts','model_snapshots',[items{k,2} '.png']));
end
close_system(mdl,0); fprintf('Model snapshots exported.\n');
end
